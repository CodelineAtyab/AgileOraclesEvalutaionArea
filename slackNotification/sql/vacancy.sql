-- 1. TABLES

CREATE TABLE vacant_jobs (
                             job_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             job_title       VARCHAR2(150) NOT NULL,
                             description     VARCHAR2(1000) NOT NULL,
                             expires_at      TIMESTAMP NOT NULL,
                             is_active       CHAR(1) DEFAULT 'Y' NOT NULL
                                 CONSTRAINT ck_vacant_jobs_active
                                     CHECK (is_active IN ('Y', 'N')),
                             created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE jobs_posting_archive (
                                      job_id          NUMBER PRIMARY KEY,
                                      job_title       VARCHAR2(150) NOT NULL,
                                      description     VARCHAR2(1000) NOT NULL,
                                      expires_at      TIMESTAMP NOT NULL,
                                      created_at      TIMESTAMP NOT NULL,
                                      archived_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE notifications (
                               notification_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               subject         VARCHAR2(200) NOT NULL,
                               body            VARCHAR2(2000) NOT NULL,
                               status          VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
                    CONSTRAINT ck_notification_status
                    CHECK (status IN ('PENDING', 'SENT')),
                               created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                               sent_at         TIMESTAMP
);

CREATE TABLE job_applications (
                                  application_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  job_id          NUMBER NOT NULL,
                                  applicant_name  VARCHAR2(150) NOT NULL,
                                  applicant_email VARCHAR2(200) NOT NULL,
                                  applied_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                                  CONSTRAINT fk_application_job
                                      FOREIGN KEY (job_id)
                                          REFERENCES vacant_jobs(job_id)
                                          ON DELETE CASCADE
);

