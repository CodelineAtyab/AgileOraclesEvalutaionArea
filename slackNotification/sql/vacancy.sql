-- 3. FUNCTION

CREATE OR REPLACE FUNCTION custom_lower
(
    p_text IN VARCHAR2
)
RETURN VARCHAR2
AS
    v_result VARCHAR2(4000) := '';
    v_char   CHAR(1);
BEGIN
FOR i IN 1 .. LENGTH(p_text)
    LOOP
        v_char := SUBSTR(p_text, i, 1);
        IF ASCII(v_char) BETWEEN 65 AND 90 THEN
            v_result := v_result || CHR(ASCII(v_char) + 32);
ELSE
            v_result := v_result || v_char;
END IF;
END LOOP;
RETURN v_result;
END custom_lower;
/

-- 4. PROCEDURES

CREATE OR REPLACE PROCEDURE register_notification
(
    p_subject IN VARCHAR2,
    p_body    IN VARCHAR2
)
AS
BEGIN
INSERT INTO notifications (subject, body)
VALUES (p_subject, p_body);
END register_notification;
/

CREATE OR REPLACE PROCEDURE process_job_description
(
    p_description IN  VARCHAR2,
    p_result      OUT VARCHAR2
)
AS
BEGIN
    p_result := custom_lower(p_description);
END process_job_description;
/

CREATE OR REPLACE PROCEDURE expire_jobs
AS
BEGIN
UPDATE vacant_jobs
SET is_active = 'N'
WHERE expires_at <= SYSTIMESTAMP
  AND is_active = 'Y';
COMMIT;
END expire_jobs;
/

-- Step 09 - Purge only safely archived inactive jobs.

CREATE OR REPLACE PROCEDURE purge_inactive_jobs
AS
BEGIN
DELETE FROM vacant_jobs v
WHERE v.is_active = 'N'
  AND EXISTS (
    SELECT 1
    FROM jobs_posting_archive a
    WHERE a.job_id = v.job_id
);
END purge_inactive_jobs;
/

-- Step 08 - Archive first, then call Step 09 purge.
CREATE OR REPLACE PROCEDURE archive_inactive_jobs
AS
BEGIN
INSERT INTO jobs_posting_archive
(job_id, job_title, description, expires_at, created_at)
SELECT
    job_id,
    job_title,
    description,
    expires_at,
    created_at
FROM vacant_jobs v
WHERE is_active = 'N'
  AND NOT EXISTS (
    SELECT 1
    FROM jobs_posting_archive a
    WHERE a.job_id = v.job_id
);

purge_inactive_jobs;
COMMIT;
END archive_inactive_jobs;
/

-- Step 10 - Implicit cursor sweep.
CREATE OR REPLACE PROCEDURE sweep_job_descriptions
AS
    v_cleaned_description VARCHAR2(4000);
BEGIN
FOR job_rec IN (
        SELECT job_id, description
        FROM vacant_jobs
        WHERE is_active = 'Y'
    )
    LOOP
        process_job_description(
            job_rec.description,
            v_cleaned_description
        );

UPDATE vacant_jobs
SET description = v_cleaned_description
WHERE job_id = job_rec.job_id;
END LOOP;
COMMIT;
END sweep_job_descriptions;
/

-- Step 12 - One daily digest using an implicit cursor.
CREATE OR REPLACE PROCEDURE create_application_digest
AS
    v_body VARCHAR2(4000) := '';
BEGIN
FOR job_rec IN (
        SELECT
            v.job_id,
            v.description,
            COUNT(a.application_id) AS application_count
        FROM vacant_jobs v
        LEFT JOIN job_applications a
            ON a.job_id = v.job_id
        GROUP BY v.job_id, v.description
        ORDER BY v.job_id
    )
    LOOP
        v_body := v_body
                  || 'Job ID: ' || job_rec.job_id
                  || ' | Description: ' || job_rec.description
                  || ' | Applications: ' || job_rec.application_count
                  || CHR(10);
END LOOP;

    register_notification('Daily Application Digest', v_body);
COMMIT;
END create_application_digest;
/

-- Step 13 - Explicit cursor handed to Spring Boot.
CREATE OR REPLACE PROCEDURE get_pending_notifications
(
    p_cursor OUT SYS_REFCURSOR
)
AS
BEGIN
OPEN p_cursor FOR
SELECT
    notification_id,
    subject,
    body,
    status,
    created_at
FROM notifications
WHERE status = 'PENDING'
ORDER BY notification_id;
END get_pending_notifications;
/


-- 5. TRIGGERS


CREATE OR REPLACE TRIGGER trg_vacancy_insert_notification
AFTER INSERT ON vacant_jobs
FOR EACH ROW
BEGIN
    register_notification(
        'New Vacancy Posted',
        'Job ID ' || :NEW.job_id || ' - ' || :NEW.job_title || ' has been posted.'
    );
END;
/

CREATE OR REPLACE TRIGGER trg_vacancy_description_update
BEFORE UPDATE OF description ON vacant_jobs
    FOR EACH ROW
DECLARE
v_cleaned_description VARCHAR2(4000);
BEGIN
    process_job_description(
        :NEW.description,
        v_cleaned_description
    );
    :NEW.description := v_cleaned_description;
END;
/

