-- D.12 — One Digest a Day

-- Create the daily digest implicit cursor

CREATE OR REPLACE PROCEDURE create_daily_application_digest
AS
    v_digest_count NUMBER := 0;
BEGIN

    FOR digest_rec IN (
        SELECT
            j.job_id,
            j.description,
            COUNT(a.application_id) AS application_count
        FROM vacant_jobs j
        LEFT JOIN job_applications a
            ON a.job_id = j.job_id
        WHERE j.is_active = 'Y'
        GROUP BY
            j.job_id,
            j.description
        ORDER BY
            j.job_id
    )
    LOOP

        DECLARE
            v_existing_count NUMBER;
        BEGIN

            SELECT COUNT(*)
            INTO v_existing_count
            FROM notifications
            WHERE subject =
                    'Daily application digest - Job ' ||
                    digest_rec.job_id
              AND created_at >=
                    CAST(TRUNC(SYSDATE) AS TIMESTAMP)
              AND created_at <
                    CAST(TRUNC(SYSDATE) + 1 AS TIMESTAMP);

            IF v_existing_count = 0 THEN

                register_notification(
                    'Daily application digest - Job ' ||
                        digest_rec.job_id,

                    'Job ID: ' ||
                        digest_rec.job_id ||
                    ' | Description: ' ||
                        digest_rec.description ||
                    ' | Applications: ' ||
                        digest_rec.application_count
                );

                v_digest_count :=
                    v_digest_count + 1;

            END IF;

        END;

    END LOOP;

    DBMS_OUTPUT.PUT_LINE(
        'New digest notifications created: ' ||
        v_digest_count
    );

END create_daily_application_digest;
/

