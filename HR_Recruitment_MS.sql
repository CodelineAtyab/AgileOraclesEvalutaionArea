-- Custome lowercase function

CREATE OR REPLACE FUNCTION custom_lowercase (
    p_text IN VARCHAR2
)
RETURN VARCHAR2
AS
    v_result VARCHAR2(32767) := '';
    v_char   CHAR(1);
BEGIN
    IF p_text IS NULL THEN
        RETURN NULL;
    END IF;
    FOR i IN 1 .. LENGTH(p_text)
    LOOP
        v_char := SUBSTR(p_text, i, 1);
        IF ASCII(v_char) BETWEEN ASCII('A') AND ASCII('Z') THEN

            v_result :=
                v_result ||
                CHR(ASCII(v_char) + 32);
        ELSE
            v_result :=
                v_result ||
                v_char;
        END IF;
    END LOOP;
    RETURN v_result;
END custom_lowercase;
/


