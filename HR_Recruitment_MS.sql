    description VARCHAR2(1000) NOT NULL,
    posted_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    archived_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_jobs_posting_archive
        PRIMARY KEY (archive_id),

