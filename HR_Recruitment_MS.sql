-- Create sweep_job_descriptions IMPLICIT CURSOR

CREATE OR REPLACE PROCEDURE sweep_job_descriptions
AS
    v_clean_description VARCHAR2(1000);
    v_processed_count   NUMBER := 0;
BEGIN
    FOR job_rec IN (
        SELECT
            job_id,
            description
        FROM vacant_jobs
        WHERE is_active = 'Y'
        ORDER BY job_id
    )
    LOOP
        v_clean_description :=
            custom_lowercase(job_rec.description);

        UPDATE vacant_jobs
        SET description = v_clean_description
        WHERE job_id = job_rec.job_id;

        v_processed_count :=
            v_processed_count + 1;
    END LOOP;
    DBMS_OUTPUT.PUT_LINE(
        'Live descriptions processed: ' ||
        v_processed_count
    );
END sweep_job_descriptions;
/


