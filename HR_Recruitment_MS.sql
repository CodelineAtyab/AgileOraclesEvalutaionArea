-- Create archive_expired_vacancies procedure 

CREATE OR REPLACE PROCEDURE archive_expired_vacancies
AS
    v_archive_count NUMBER;
BEGIN

    INSERT INTO jobs_posting_archive (
        job_id,
        job_title,
        description,
        posted_at,
        expires_at
    )
    SELECT
        j.job_id,
        j.job_title,
        j.description,
        j.posted_at,
        j.expires_at
    FROM vacant_jobs j
    WHERE j.is_active = 'N'
      AND NOT EXISTS (
          SELECT 1
          FROM jobs_posting_archive a
          WHERE a.job_id = j.job_id
      );

    v_archive_count := SQL%ROWCOUNT;

    DBMS_OUTPUT.PUT_LINE(
        'Vacancies archived: ' || v_archive_count
    );

END archive_expired_vacancies;
