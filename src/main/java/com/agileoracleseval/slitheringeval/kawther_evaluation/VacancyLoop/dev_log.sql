--v_batch_time :UPDATE--
CREATE OR REPLACE PROCEDURE get_pending_notifications (p_cursor OUT SYS_REFCURSOR)
AS
  v_batch_time TIMESTAMP := SYSTIMESTAMP;
BEGIN
  UPDATE notification_outbox
     SET delivered_flag = 'Y',
         delivered_on   = v_batch_time
   WHERE delivered_flag = 'N';
  OPEN p_cursor FOR
    SELECT notification_id, job_id, msg_category, msg_subject, msg_body, generated_on
    FROM notification_outbox
    WHERE delivered_on = v_batch_time
    ORDER BY notification_id;
  COMMIT;
END get_pending_notifications;
/
--Procedure GET_PENDING_NOTIFICATIONS compiled--
--OPEN/FETCH/EXIT WHEN NOTFOUND/CLOSE--
DECLARE
  v_cursor          SYS_REFCURSOR;
  v_notification_id notification_outbox.notification_id%TYPE;
  v_job_id          notification_outbox.job_id%TYPE;
  v_category        notification_outbox.msg_category%TYPE;
  v_subject         notification_outbox.msg_subject%TYPE;
  v_body            notification_outbox.msg_body%TYPE;
  v_generated       notification_outbox.generated_on%TYPE;
BEGIN
  get_pending_notifications(v_cursor);
  LOOP
    FETCH v_cursor INTO v_notification_id, v_job_id, v_category, v_subject, v_body, v_generated;
    EXIT WHEN v_cursor%NOTFOUND;
    DBMS_OUTPUT.PUT_LINE(v_notification_id || ' | ' || v_category || ' | ' || v_subject);
  END LOOP;
  CLOSE v_cursor;
END;
