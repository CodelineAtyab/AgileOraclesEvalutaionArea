-- ============================================================
-- The Vacancy Loop - Schema & Seed Script
-- Deliverable #2. Safe to run more than once (idempotent creates)
-- because the ground rules say "assume nothing about the environment".
--
-- Fixed by the brief (do not rename): vacant_jobs, jobs_posting_archive,
-- job_applications, the expires_at column, and register_notification
-- (added in the next script). Everything else below (table/column
-- names beyond those, the notification outbox table, and all seed
-- data) is our own modelling choice - see erd/erd.md for the reasoning.
-- ============================================================

-- ---------- VACANT_JOBS : the live board ----------
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE vacant_jobs (
      job_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      job_title       VARCHAR2(100)  NOT NULL,
      job_description VARCHAR2(1000) NOT NULL,
      posted_on       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
      expires_at      TIMESTAMP      NOT NULL,
      active_flag     CHAR(1)        DEFAULT ''Y'' NOT NULL
                       CONSTRAINT ck_vacant_jobs_active CHECK (active_flag IN (''Y'',''N''))
    )';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF; -- -955 = name already used by an existing object
END;
/

-- ---------- JOBS_POSTING_ARCHIVE : where expired postings go to die ----------
-- Same shape as vacant_jobs minus the active flag, plus an archived_on stamp.
-- No FK back to vacant_jobs on purpose - see erd/erd.md for why.
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE jobs_posting_archive (
      job_id          NUMBER PRIMARY KEY,
      job_title       VARCHAR2(100)  NOT NULL,
      job_description VARCHAR2(1000) NOT NULL,
      posted_on       TIMESTAMP      NOT NULL,
      expires_at      TIMESTAMP      NOT NULL,
      archived_on     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
    )';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

-- ---------- NOTIFICATION_OUTBOX : the outbox for Slack ----------
-- job_id is kept for traceability only - not a hard FK (see erd/erd.md).
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE notification_outbox (
      notification_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      job_id             NUMBER,
      msg_category        VARCHAR2(20)   DEFAULT ''JOB_POSTED'' NOT NULL
                          CONSTRAINT ck_notif_category CHECK (msg_category IN (''JOB_POSTED'',''DAILY_DIGEST'')),
      msg_subject        VARCHAR2(200)  NOT NULL,
      msg_body           VARCHAR2(1000) NOT NULL,
      generated_on       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
      delivered_flag     CHAR(1)        DEFAULT ''N'' NOT NULL
                          CONSTRAINT ck_notif_delivered CHECK (delivered_flag IN (''Y'',''N'')),
      delivered_on       TIMESTAMP
    )';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

-- ---------- JOB_APPLICATIONS : many candidates, one posting ----------
-- Real FK, ON DELETE CASCADE: an application only makes sense while its
-- posting is live; once the posting is purged (already archived), its
-- applications go with it rather than becoming orphans.
-- digested_flag makes send_daily_application_digest safe to run any
-- number of times: each application is only ever counted into one
-- digest notification, no matter how often the job fires (see
-- 02_procedures.sql for the procedure that relies on it).
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE job_applications (
      application_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      job_id            NUMBER NOT NULL
                         CONSTRAINT fk_job_applications_job
                         REFERENCES vacant_jobs (job_id) ON DELETE CASCADE,
      candidate_name    VARCHAR2(100)  NOT NULL,
      candidate_email   VARCHAR2(150),
      submitted_on      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
      digested_flag     CHAR(1)        DEFAULT ''N'' NOT NULL
                         CONSTRAINT ck_job_app_digested CHECK (digested_flag IN (''Y'',''N''))
    )';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

