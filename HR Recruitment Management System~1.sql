CREATE OR REPLACE PROCEDURE ensure_archive_table
IS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM user_tables WHERE table_name = 'JOBS_POSTING_ARCHIVE';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE jobs_posting_archive (
                job_id      NUMBER PRIMARY KEY,
                title       VARCHAR2(200)  NOT NULL,
                description VARCHAR2(4000) NOT NULL,
                posted_by   VARCHAR2(100)  NOT NULL,
                expires_at  TIMESTAMP      NOT NULL,
                created_at  TIMESTAMP      NOT NULL,
                archived_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
            )]';
    END IF;
END ensure_archive_table;
/
--Archive + purge together
CREATE OR REPLACE PROCEDURE archive_and_purge
IS
BEGIN
    ensure_archive_table;

    INSERT INTO jobs_posting_archive
        (job_id, title, description, posted_by, expires_at, created_at)
    SELECT job_id, title, description, posted_by, expires_at, created_at
      FROM vacant_jobs
     WHERE is_active = 'N';

    DELETE FROM vacant_jobs WHERE is_active = 'N';

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END archive_and_purge;
/

CREATE OR REPLACE PROCEDURE sweep_descriptions
IS
BEGIN
    FOR r IN (SELECT job_id, description
                FROM vacant_jobs
               WHERE is_active = 'Y'
                 AND description != my_lower(description))
    LOOP
        UPDATE vacant_jobs
           SET description = my_lower(r.description)
         WHERE job_id = r.job_id;
    END LOOP;
    COMMIT;
END sweep_descriptions;
/

--count how many applicant applied for a job
CREATE OR REPLACE PROCEDURE daily_digest
IS
BEGIN
    FOR r IN (SELECT j.job_id,
                     j.description,
                     COUNT(a.application_id) AS applicant_count
                FROM vacant_jobs j
                LEFT JOIN job_applications a ON a.job_id = j.job_id
               WHERE j.is_active = 'Y'
               GROUP BY j.job_id, j.description)
    LOOP
    DECLARE
                v_exists NUMBER;
            BEGIN
                SELECT COUNT(*) INTO v_exists
                  FROM notification
                 WHERE job_id = r.job_id
                   AND notif_type = 'DAILY_DIGEST'
                   AND TRUNC(created_at) = TRUNC(SYSDATE);
        IF v_exists = 0 THEN
            register_notification(
                r.job_id,
                'DAILY_DIGEST',
                'Daily digest for job ' || r.job_id,
                'Job ' || r.job_id || ' — ' || r.description ||
                ' — applicants: ' || r.applicant_count
        );
        END IF;
        END;
    END LOOP;
    COMMIT;
END daily_digest;
