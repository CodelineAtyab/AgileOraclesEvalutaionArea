 CREATE OR REPLACE PROCEDURE register_notification (
    p_job_id  IN NUMBER,
    p_type    IN VARCHAR2,
    p_subject IN VARCHAR2,
    p_body    IN VARCHAR2
)
IS
BEGIN
    INSERT INTO notification (job_id, notif_type, subject, body, status)
    VALUES (p_job_id, p_type, p_subject, p_body, 'PENDING');
END register_notification;
/

--Trigger for a new posting
CREATE OR REPLACE TRIGGER trg_vj_new_posting
AFTER INSERT ON vacant_jobs
FOR EACH ROW
BEGIN
    register_notification(
        :NEW.job_id,
        'NEW_POSTING',
        'New vacancy: ' || :NEW.title,
        'A new job has been posted: ' || :NEW.description
    );
END;
/

--Trigger for a description edit
CREATE OR REPLACE TRIGGER trg_vj_lowercase
BEFORE INSERT OR UPDATE OF description ON vacant_jobs
FOR EACH ROW
BEGIN
    :NEW.description := my_lower(:NEW.description);
END;
/

--Expiry
CREATE OR REPLACE PROCEDURE expire_postings
IS
BEGIN
    UPDATE vacant_jobs
       SET is_active = 'N'
     WHERE is_active = 'Y'
       AND expires_at < SYSTIMESTAMP;
    COMMIT;
END expire_postings;
