-- a function that convert to lower case
CREATE OR REPLACE FUNCTION my_lower (p_text IN VARCHAR2)
    RETURN VARCHAR2
    DETERMINISTIC
IS
    v_result VARCHAR2(4000) := NULL;
    v_char   VARCHAR2(1);
    v_code   PLS_INTEGER;
BEGIN
    -- Guard. In Oracle an empty string IS NULL, so this covers both.
    -- Without it, LENGTH(NULL) is NULL, the loop never runs, and you
    -- silently return NULL anyway -- but being explicit documents intent.
    IF p_text IS NULL THEN
        RETURN NULL;
    END IF;
 
    FOR i IN 1 .. LENGTH(p_text) LOOP
        v_char := SUBSTR(p_text, i, 1);
        v_code := ASCII(v_char);
 
        IF v_code BETWEEN 65 AND 90 THEN      -- 'A' .. 'Z'
            v_result := v_result || CHR(v_code + 32);
        ELSE
            v_result := v_result || v_char;   -- digits, spaces, Arabic, punctuation
        END IF;
    END LOOP;
 
    RETURN v_result;
END my_lower;
/

