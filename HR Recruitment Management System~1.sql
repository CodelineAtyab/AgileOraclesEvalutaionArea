CREATE TABLE vacant_jobs (
    job_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR2(200)  NOT NULL,
    description  VARCHAR2(4000) NOT NULL,
    posted_by    VARCHAR2(100)  DEFAULT USER NOT NULL,
    is_active    CHAR(1)        DEFAULT 'Y' NOT NULL,
    expires_at   TIMESTAMP      NOT NULL,
    created_at   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_vj_active  CHECK (is_active IN ('Y','N')),
    CONSTRAINT ck_vj_expiry  CHECK (expires_at > created_at)
);

CREATE TABLE notification (
    notification_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id          NUMBER,
    notif_type      VARCHAR2(30)   NOT NULL,
    subject         VARCHAR2(400)  NOT NULL,
    body            VARCHAR2(4000) NOT NULL,
    status          VARCHAR2(10)   DEFAULT 'PENDING' NOT NULL,
    created_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    sent_at         TIMESTAMP,
    CONSTRAINT fk_notif_job  FOREIGN KEY (job_id)
        REFERENCES vacant_jobs(job_id) ON DELETE SET NULL,
    CONSTRAINT ck_notif_type CHECK (notif_type IN ('NEW_POSTING','DAILY_DIGEST')),
    CONSTRAINT ck_notif_stat CHECK (status IN ('PENDING','SENT','FAILED')),
    CONSTRAINT ck_notif_sent CHECK ((status = 'SENT' AND sent_at IS NOT NULL)
                                 OR (status != 'SENT'))
);

CREATE TABLE job_applications (
    application_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id          NUMBER        NOT NULL,
    applicant_name  VARCHAR2(150) NOT NULL,
    applicant_email VARCHAR2(150) NOT NULL,
    applied_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_app_job FOREIGN KEY (job_id)
        REFERENCES vacant_jobs(job_id) ON DELETE CASCADE,
    CONSTRAINT uq_app_once UNIQUE (job_id, applicant_email)
);

CREATE TABLE jobs_posting_archive (
                job_id       NUMBER         PRIMARY KEY,
                title        VARCHAR2(200)  NOT NULL,
                description  VARCHAR2(4000) NOT NULL,
                posted_by    VARCHAR2(100)  NOT NULL,
                expires_at   TIMESTAMP      NOT NULL,
                created_at   TIMESTAMP      NOT NULL,
                archived_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);


