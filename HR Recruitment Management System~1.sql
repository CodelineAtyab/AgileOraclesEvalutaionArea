--handing the rows to Java
CREATE OR REPLACE PROCEDURE get_pending_notifications (
    p_result OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN p_result FOR
        SELECT notification_id, job_id, subject, body, created_at
          FROM notification
         WHERE status = 'PENDING'
         ORDER BY created_at;
END get_pending_notifications;
