-- clean slate, drop old tables if they exist
BEGIN
  FOR r IN (
    SELECT table_name FROM user_tables
    WHERE table_name IN ('JOB_APPLICATIONS','JOBS_POSTING_ARCHIVE','NOTIFICATIONS','VACANT_JOBS')
  ) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || r.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- the live job board, HR inserts here
create table vacant_jobs (
  job_id       number generated by default as identity primary key,
  title        varchar2(150) not null,
  description  varchar2(2000) not null,
  posted_at    timestamp default systimestamp not null,
  expires_at   timestamp not null,
  job_status   varchar2(10) default 'ACTIVE' not null
               check (job_status in ('ACTIVE','EXPIRED','ARCHIVED'))
);

-- same shape as vacant_jobs, minus job_status
create table jobs_posting_archive (
  job_id       number primary key,
  title        varchar2(150) not null,
  description  varchar2(2000) not null,
  posted_at    timestamp not null,
  expires_at   timestamp not null,
  archived_at  timestamp default systimestamp not null
);

-- every message the system creates lands here
create table notifications (
  notification_id  number generated by default as identity primary key,
  subject          varchar2(200) not null,
  body             varchar2(2000) not null,
  created_at       timestamp default systimestamp not null,
  sent_flag        char(1) default 'N' not null
                   check (sent_flag in ('Y','N'))
);

-- candidates who applied, many rows can point to one job
create table job_applications (
  application_id  number generated by default as identity primary key,
  job_id          number not null references vacant_jobs(job_id),
  applicant_name  varchar2(150) not null,
  applied_at      timestamp default systimestamp not null
);

